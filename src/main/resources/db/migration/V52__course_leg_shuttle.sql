--
-- 왜 — 거제 9경 아홉 중 **7경(공곶이·내도)과 8경(지심도)이 코스에 한 번도 들어가지 못했다**(2026-09-22 실측:
-- 코스 33개가 쓰는 스팟이 14곳뿐이고 그 둘은 0회). 버스로는 닿지 않는 섬이고, 둘을 잇는 배는 **도선**인데
-- 지금 스키마의 배 구간(FERRY)은 **유람선 상품**(ferry_courses)만 가리킬 수 있다:
--
--   chk_leg_ferry_course : (mode = 'FERRY') = (ferry_course_id IS NOT NULL)
--
-- 도선(shuttle_docks · shuttle_departures, V31)은 그 표에 없다. 그래서 담을 자리가 없었다.
--
-- ⚠️ FERRY 제약을 푸는 길도 있었지만 쓰지 않는다. 유람선과 도선은 **다른 것**이다 —
--    유람선은 상품(코스 · 선상/상륙 · 예약 상품 페이지)이고, 도선은 섬으로 건너가는 배(왕복 · 운항사 전화)다.
--    「FERRY 면 유람선 상품이 있다」는 불변식을 깨면 화면이 예약 링크를 찾지 못하는 버그가 조용히 생긴다.
--
-- ⚠️ **이 파일은 값 하나만 더한다.** Postgres 는 enum 에 값을 더한 트랜잭션 안에서 그 값을 **쓰지 못한다**
--    (55P04 unsafe use of new value). Flyway 는 스크립트 하나를 한 트랜잭션으로 돌리므로,
--    제약(mode = 'SHUTTLE')은 V53 에서, 코스 적재는 V54 에서 한다. psql 로 손수 돌리면 자동 커밋이라
--    한 파일에 몰아도 통과해 **이 함정이 배포에서만 터진다**(2026-09-22 실제로 겪었다).

