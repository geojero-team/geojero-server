-- V54 (2026-09-22): 섬 코스 넷 — 거제 9경 7경(공곶이·내도) · 8경(지심도)을 코스에 처음 넣는다
--
-- 왜 — 코스 33개가 쓰는 스팟이 **14곳뿐**이었다(2026-09-22 실측). 9경 아홉 중 둘은 코스가 하나도 없었다:
--   · 지심도(8경) · 공곶이·내도(7경) — 버스 정류장이 원문 격자에 없다(NO_STOP_IN_TIMETABLE).
-- 사용자가 하차 기준을 정했다(2026-09-22): **지심도는 장승포 기준, 공곶이는 구조라 기준**.
-- 다만 원문 격자에 「장승포」 열은 없다 — 「장승포1구」가 시각 있는 정차 4건뿐이다. 그래서 버스는 **능포**에
-- 내리고(시각 있는 정차 612건 · 33개 노선) 장승포 선착장까지 걸어간다. 그 걷는 거리는 아래에 적는다.
-- 와현도 4000번 12편뿐이라 쓰지 않고 공곶이는 구조라에서 걸어간다(사용자가 준 22 · 23 · 67 · 24-2 는 격자에 와현 열이 없다).
--
-- ── 규칙(V37 과 같다. 환승 규칙만 2026-09-22 사용자 확정값) ──────────────────────
--   · 스팟마다 60분 이상 머문다 · 마지막 스팟 도착 18:30 이하 · 복귀 20:00 이하 · 07:00 전 출발 지양
--   · 환승은 **같은 이름 정류장**에서만, 여유 15분 이상, 왕복 전체 2회까지 — 넷 다 환승 0회로 성립했다
--   · 시각은 전부 원문이다: 버스는 거제시 BIS(2026-08-18), 도선은 운항사 안내(V31)
--
-- ── 걷는 거리 · 배 시간은 원문 좌표에서 잰다 ─────────────────────────────────
--   두 점 사이 **직선거리**(pois · shuttle_docks · boarding_stops 좌표)다. 화면도 직선거리로 말한다(2026-09-18).
--     능포종점 ↔ 장승포 선착장    1,927m      장승포 선착장 ↔ 양지암조각공원  1,750m
--     능포종점 ↔ 양지암조각공원      303m      지세포 정류장 ↔ 거제씨월드        775m
--     지세포 정류장 ↔ 조선해양문화관 662m      구조라 선착장 ↔ 공곶이          2,128m
--   ⚠️ **편을 고를 때만** 걷는 분으로 바꿨다 — 시속 4km, 그 위에 사용자가 정한 여유 15분을 더 얹었다.
--      걷는 분은 어느 원문에도 없으므로 **화면에 적지 않는다**(2026-09-16 사용자 결정). DB 에도 넣지 않는다.
--   ⚠️ 구조라 정류장 ↔ 구조라 선착장은 정류장 좌표가 어디에도 없어 재지 못했다 — 10분으로 **가정**했다.
--      마을 안(구조라로 21)이라 크게 어긋나지 않겠지만 사람이 확인해야 한다.
--   · 배 시간은 원문이다: 구조라→내도 10분(shuttle_docks.trip_note 「관광시간 10분」),
--     장승포→지심도 20분(shuttle_departures 의 들어가는 편 08:30 ↔ 나오는 편 08:50).
--
-- ── 구간 모양 ───────────────────────────────────────────────────────────────
--   버스 구간과 도선 구간이 **같은 섬에 닿는다**. 화면은 두 구간이 같은 곳에 닿으면 점을 한 번만 찍는다 —
--   버스는 능포(구조라)까지 데려다주고 점은 배가 내려 주는 섬에 찍힌다. 돌아오는 도선은 선착장으로 나오므로
--   닿는 곳이 없다(to_poi_id 가 NULL). 유람선의 돌아오는 편(V36)과 같은 자리다.
--   ⚠️ chk_leg_endpoints 가 양끝 NULL 을 막아서 버스 구간은 섬 POI 를 가리킨다 — 「버스가 섬까지 간다」는
--      뜻이 아니라 「이 버스를 타고 저기로 간다」는 뜻이다(다른 코스의 버스 구간과 같은 규칙).
--
-- ── 대표 열에 넣는다 ─────────────────────────────────────────────────────────
--   featured_rank 11~14 · 배지는 코스마다 하나(2026-09-22 사용자) — 9경 둘 · 분류 둘로 갈랐다.
--   넷 다 9경 배지를 달면 「배지가 전부 9경이라 무엇이 다른지 말하지 않는다」(코스재설계 §0)로 되돌아간다.

