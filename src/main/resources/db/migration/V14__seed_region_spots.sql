-- 권역별 스팟 9곳 추가 (2026-09-12 팀 결정)
--
-- 왜 넣나: 판정을 빼고 **우리가 짠 코스**를 보여주기로 바꾸면서 스팟 선정 기준이 바뀌었다.
-- 기존 8곳은 거제 9경을 받아 **일부러 전역에 분산**시킨 것이었다(§6 남부4·동부1·중부1·북부1·서부1).
-- 판정 서비스에는 그게 맞았지만 — §1의 "관광지는 섬 전역 분산, 문제가 남부에 집중"을
-- 보여주는 데 분산이 유리했다 — **코스 서비스에는 불리하다.** 권역별로 뭉쳐 있어야
-- 한 줄로 꿸 수 있고, 분산된 채로는 남부 코스 하나만 나온다(중부·북부·서부가 각 1곳).
--
-- 그래서 팀원이 권역별로 조사한 목록을 받았다. 이 9곳이 들어오면 권역별로 이렇게 된다:
--   북부 3 (매미성 + 맹종죽 + 김영삼) / 동부 5 (외도 + 조선해양 + 씨월드 + 양지암 + 옥포대첩)
--   남부 6 (학동·해금강·바람의언덕·도장포·외도... + 여차홍포) / 서부 3 (식물원 + 청마 + 관아)
--   중부 1 (포로수용소)
-- → 남부 하나였던 코스가 권역 네 개로 늘어난다.
--
-- ⚠️ 정본은 TourAPI다 (기준문서 §7 「관광지 정보의 정본은 TourAPI다」, CLAUDE.md 절대규칙 5).
-- 이름·주소·좌표·분류를 전부 실호출로 확인했다(2026-09-12, areaBasedList2 + detailCommon2,
-- lDongRegnCd=48 / lDongSignguCd=310 거제 등록분 464건 전량 대조).
-- 팀원 목록과 **이름이 다른 것이 셋** 있었고, 전부 TourAPI를 따랐다:
--   「거제맹종죽 테마파크」  → 등록명 **「거제맹종죽테마공원」**
--   「거제 기성관」          → 등록명 없음. **「거제현 관아」(128033)** 안의 객사 건물이다.
--                              소개문이 "현재는 기성관과 질청이 남아 있으며"로 명시한다.
--   「여차,홍포 해안비경」   → 등록명 **「여차,홍포간 해안도로」(2652447)**.
--                              DB에 이미 있는 `여차몽돌해변`(126579)과는 **1.5km 떨어진 다른 곳**이다.
--
-- 「거제조선해양문화관」(2783983)과 「거제어촌민속전시관」(1622179)은 같은 주소
-- (지세포해안로 41)에 contentId가 둘로 등록돼 있다. 소개문이 *"한번 발권으로 1관 거제어촌
-- 민속 전시관과 2관 거제 조선해양 문화관을 같이 관람"*이라 적는다 → **스팟 하나**로 넣고
-- 대표를 2783983으로 잡는다. 씨월드는 15번지·다른 운영사라 별도 스팟이다.
--
-- 명사해수욕장(126577)은 **뺐다.** 행과 좌표는 이미 있으나 theme가 NULL이라 화면에 안 뜬다
-- (V11). 살리지 않은 이유는 하나로 좁혀졌다 — **쓸 수 있는 사진이 없다.**
--   관광정보 API: 대표사진 있으나 cpyrhtDivCd=**Type3**(제3자 저작권) → 서버가 장 단위로 거른다
--   관광사진 API: '명사' 75건 전량 확인 → 완도 명사십리·신안 명사십리·제주 광명사뿐.
--                 촬영지가 '거제'인 사진 679장을 다 훑어도 명사가 없다.
-- photo_keyword='명사'가 이미 걸려 있었고 빈손이었다. 사진이 생기면 theme 한 줄로 되살린다.
--
-- tier는 **전부 NULL로 둔다.** §2 「스팟별 접근성 티어」에 이 9곳이 없고, 하차 정류소도
-- 아직 [미확인]이다. 내릴 곳을 모르는데 접근 난이도를 단정하지 않는다(절대규칙 1).
-- 거제식물원·신선대가 같은 이유로 NULL인 선례가 있다(V3 주석).
--
-- nearest_stop_id·walk_min_from_stop도 넣지 않는다 — 팀원이 시간표를 재조사하는 중이고,
-- 정류소 이름이 확정되면 그때 잇는다.
--
-- photo_keyword 주의: **관광사진 API 제목이 관광정보 API 제목과 다르다.**
--   관광정보 「거제조선해양문화관」 ↔ 관광사진 「조선해양전시관」(30장)·「거제조선해양전시관」(18장)
--   관광정보 「옥포대첩기념공원」   ↔ 관광사진 「옥포대첩기념관」(23장)
--   관광정보 「여차,홍포간 해안도로」 ↔ 관광사진 「홍포여차해안도로」(15장)  ← 순서가 거꾸로다
-- 그래서 정식명이 아니라 **양쪽에 공통으로 든 부분**을 키워드로 넣는다.
-- 키워드가 없는 넷(씨월드·양지암·청마·관아)은 관광사진에 0건이지만 상세 사진이
-- 전부 cpyrhtDivCd=Type1이라 그대로 쓸 수 있다.

