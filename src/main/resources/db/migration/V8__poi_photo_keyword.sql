-- 관광사진 API(공공누리 제1유형)로 사진을 찾을 때 쓸 검색어.
--
-- KorService2 사진이 전 장 cpyrhtDivCd Type3라 하나도 못 쓰는 POI가 있다(2026-09-10 실측:
-- 도장포유람선·신선대·명사해수욕장). 관광사진 API는 별도 승인분이고 공공누리 제1유형이라
-- 출처만 밝히면 쓸 수 있어서, 그쪽에서 대신 찾는다.
--
-- **정식 명칭이 아니라 검색에 걸리는 말을 넣는다.** '도장포유람선'으로 찾으면 0건이고
-- '도장포'로 찾아야 "도장포 유람선선착장" 3장이 나온다. 걸러내기(제목에 이 말이 있고
-- 촬영지가 거제)도 이 값으로 하므로, 너무 짧으면 남의 사진이 섞인다.
--
-- 명사해수욕장은 지금 0건이지만 넣어둔다 — 나중에 사진이 등록되면 코드 수정 없이 잡힌다.
ALTER TABLE pois ADD COLUMN photo_keyword varchar(50);

UPDATE pois p SET photo_keyword = v.kw
FROM (VALUES
  ('도장포유람선', '도장포'),
  ('신선대',       '신선대'),
  ('명사해수욕장', '명사')
) AS v(poi_name, kw)
WHERE p.poi_name = v.poi_name;
