-- 화면 이름을 "짧게"에서 "혼동 없게"로 옮긴다.
--
-- V4는 지도 이름표를 짧게 하려고 '외도'·'학동'·'도장포'로 줄였는데, 셋 다 그 자체로
-- 다른 것을 가리키는 말이었다:
--   외도   → 섬 이름. 관광지는 '외도보타니아'이고 카카오 지도도 그렇게 찍는다.
--            같은 자리에 이름이 둘이라 다른 곳처럼 보였다.
--   학동   → 마을 이름. 게다가 모래가 아니라 몽돌(자갈)해변이라 '해변'만 붙이면
--            모래사장으로 오해한다. 정식 '학동흑진주몽돌해변'은 이름표로 너무 길다.
--   도장포 → 마을 이름. 이 POI는 마을이 아니라 유람선 선착장이다.
--
-- 정류장 이름(BIS 원문)은 이것과 별개다. 판정 화면의 '학동 하차'는 그대로 '학동'이다.
UPDATE pois p SET short_name = v.short_name
FROM (VALUES
  ('외도보타니아',       '외도보타니아'),
  ('학동흑진주몽돌해변', '학동몽돌해변'),
  ('도장포유람선',       '도장포유람선')
) AS v(poi_name, short_name)
WHERE p.poi_name = v.poi_name;
