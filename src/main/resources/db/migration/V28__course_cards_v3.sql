-- 1) 거제 9경 번호 -----------------------------------------------------------------
ALTER TABLE pois ADD COLUMN nine_scenic_no smallint;

COMMENT ON COLUMN pois.nine_scenic_no IS
  '거제시 공식 「거제 9경」 번호(1~9). NULL 이면 9경이 아니다. 기준문서 §6 표 — 채택한 7경만 번호가 있다.';

UPDATE pois p SET nine_scenic_no = v.no
FROM (VALUES
  ('126224',  1),   -- 1경 거제 해금강
  ('129479',  2),   -- 2경 바람의 언덕과 신선대 → 바람의언덕
  ('126581',  3),   -- 3경 외도보타니아
  ('127658',  4),   -- 4경 학동 흑진주 몽돌해변 → 학동흑진주몽돌해변
  ('2648073', 5),   -- 5경 거제 식물원 → 거제식물원
  ('127938',  6),   -- 6경 거제도포로수용소유적공원
  ('2536133', 9)    -- 9경 매미성
) AS v(cid, no)
WHERE p.tour_content_id = v.cid;

-- 코스의 9경 수를 공식 번호로 다시 센다 — V20 이 매미성(9경 9번)을 빠뜨려 4-03 · 4-07 · 4-08 이 하나 적었다. 나머지는 값이 같다.
UPDATE courses c SET nine_scenic_count = sub.numbered
FROM (
  SELECT cp.course_id, count(p.nine_scenic_no) AS numbered
  FROM course_pois cp JOIN pois p ON p.poi_id = cp.poi_id
  GROUP BY cp.course_id
) AS sub
WHERE sub.course_id = c.course_id AND c.course_code IS NOT NULL;

