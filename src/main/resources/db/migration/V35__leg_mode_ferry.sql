-- V35 (2026-09-16): 코스 구간에 **배**를 담을 수 있게 한다 — leg_mode 에 FERRY 를 더한다.
--
-- 왜 필요한가: 거제 9경 아홉 중 셋(3경 외도보타니아 · 7경 내도 · 8경 지심도)이 **배로만 간다**.
-- 시간표는 진작 있었다 — 외도 유람선 1,081편(V23·V24) · 도선(V31). 그런데 V16 의
-- leg_mode 가 BUS·SAME_STOP 둘뿐이라 코스에 담을 자리가 없어, 추천 코스 23개에 외도가 0개다.
-- 기준문서 §9 「④ 추천 코스에 외도 넣기(배 구간)」가 이 일이다.
--
-- ⚠️ 이 마이그레이션은 값 추가만 한다. PostgreSQL 은 ALTER TYPE ... ADD VALUE 로 더한 값을
-- **같은 트랜잭션 안에서 쓸 수 없다**. 그래서 컬럼·제약·코스 적재는 V36 으로 나눴다.

ALTER TYPE leg_mode ADD VALUE IF NOT EXISTS 'FERRY';
